param([Parameter(Mandatory)][ValidateSet('windows','android')][string]$Platform,
    [ValidateSet('arm64','x64')][string]$AndroidArch = 'arm64',
    [ValidateSet('debug','profile','release')][string]$Mode = 'release',
    [string]$Target = 'lib/main.dart',
    [switch]$Production,
    [switch]$StandardDebugKey)
. "$PSScriptRoot/env.ps1"
if ($Platform -eq 'android' -and $Mode -eq 'release' -and $AndroidArch -ne 'arm64') {
    throw 'Release APKs are ARM64-only. Disposable x64 harnesses must use debug/profile mode.'
}
if ($Production -and ($Mode -ne 'release' -or $Target -ne 'lib/main.dart' -or $AndroidArch -ne 'arm64')) {
    throw 'Production delivery requires release mode, main.dart and ARM64 Android.'
}
if ($Production -and $StandardDebugKey) { throw 'Production never permits debug signing.' }
$previousDebugKey = $env:RECIPE_DEBUG_KEYSTORE
if ($StandardDebugKey) { $env:RECIPE_DEBUG_KEYSTORE = $null }
$previousProduction = $env:COOKDEX_PRODUCTION
$env:COOKDEX_PRODUCTION = if ($Production) { '1' } else { '0' }
$rustFeatures = if ($Production) { @('--features', 'cookdex-bridge/production-sync') } else { @() }
$dartIdentity = if ($Production) { '--dart-define=COOKDEX_DEV=false' } else { '--dart-define=COOKDEX_DEV=true' }
Push-Location $flutterRoot
try {
    flutter pub get --offline
    Assert-FlutterExit
    if ($Platform -eq 'windows') {
        cargo build --manifest-path rust/Cargo.toml --release --locked --offline -p cookdex-bridge @rustFeatures
        Assert-FlutterExit
        flutter build windows "--$Mode" --target $Target $dartIdentity
        Assert-FlutterExit
    } else {
        if ($Mode -eq 'release' -and -not $Production) {
            if (-not $StandardDebugKey -and -not $env:RECIPE_DEBUG_KEYSTORE) {
                $existingDevKey = Join-Path (Split-Path $cookdexRoot -Parent) 'cookdex-secrets/android/recipe-debug.keystore'
                if (Test-Path -LiteralPath $existingDevKey -PathType Leaf) { $env:RECIPE_DEBUG_KEYSTORE = $existingDevKey }
            }
            # An explicit override must exist. A public clone otherwise uses
            # Android's standard debug key, generated by Gradle when needed.
            if ($env:RECIPE_DEBUG_KEYSTORE -and -not (Test-Path -LiteralPath $env:RECIPE_DEBUG_KEYSTORE -PathType Leaf)) {
                throw 'The explicitly selected dev signing key is missing.'
            }
        }
        $rustTarget = if ($AndroidArch -eq 'arm64') { 'aarch64-linux-android' } else { 'x86_64-linux-android' }
        $abi = if ($AndroidArch -eq 'arm64') { 'arm64-v8a' } else { 'x86_64' }
        cargo build --manifest-path rust/Cargo.toml --release --locked --offline -p cookdex-bridge @rustFeatures --target $rustTarget
        Assert-FlutterExit
        $jni = "android/app/src/main/jniLibs/$abi"
        # Flutter filters its own engine ABI, but can package stale jniLibs.
        # Remove only our known generated probe library for the other ABI.
        foreach ($otherAbi in @('arm64-v8a', 'x86_64')) {
            $otherProbe = Join-Path $flutterRoot "android/app/src/main/jniLibs/$otherAbi/libcookdex_core_probe.so"
            if (Test-Path -LiteralPath $otherProbe) { Remove-Item -LiteralPath $otherProbe }
            if ($otherAbi -ne $abi) {
                $otherBridge = Join-Path $flutterRoot "android/app/src/main/jniLibs/$otherAbi/libcookdex_bridge.so"
                if (Test-Path -LiteralPath $otherBridge) { Remove-Item -LiteralPath $otherBridge }
            }
        }
        New-Item -ItemType Directory -Force $jni | Out-Null
        Copy-Item "rust/target/$rustTarget/release/libcookdex_bridge.so" $jni -Force
        flutter build apk "--$Mode" --target $Target --target-platform "android-$AndroidArch" $dartIdentity
        Assert-FlutterExit
    }
} finally { Pop-Location; $env:COOKDEX_PRODUCTION = $previousProduction; $env:RECIPE_DEBUG_KEYSTORE = $previousDebugKey }
